from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch

from datasets import build_loaders
from models import build_model
from utils.visualization import denormalize, plot_histories

EXPERIMENTS = {
    "U-Net": Path("runs/unet"),
    "Attention U-Net": Path("runs/attention_unet"),
    "Transformer U-Net": Path("runs/transformer_unet"),
    "Proposed": Path("runs/proposed_model"),
}
MACRO_PREFIX = {
    "U-Net": "UNet",
    "Attention U-Net": "AttentionUNet",
    "Transformer U-Net": "TransformerUNet",
    "Proposed": "Proposed",
}
METRIC_MACROS = ("Dice", "IoU", "Precision", "Recall", "HD", "Params", "Latency")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate paper tables, macros, curves, and qualitative figures.")
    parser.add_argument("--device", default=None)
    parser.add_argument("--qualitative-samples", type=int, default=4)
    return parser.parse_args()


def fmt(value: float, digits: int = 4) -> str:
    return f"{value:.{digits}f}"


def write_macros(metrics_by_name: dict[str, dict]) -> None:
    lines = ["% Auto-generated by generate_paper_assets.py. Do not edit manually."]
    if metrics_by_name:
        best_name = max(metrics_by_name, key=lambda n: metrics_by_name[n]["dice_mean"])
        best = metrics_by_name[best_name]
        unet = metrics_by_name.get("U-Net")
        gain = best["dice_mean"] - unet["dice_mean"] if unet else 0.0
        lines.extend(
            [
                f"\\newcommand{{\\BestModelName}}{{{best_name}}}",
                f"\\newcommand{{\\BestDice}}{{{fmt(best['dice_mean'])}}}",
                f"\\newcommand{{\\BestIoU}}{{{fmt(best['iou_mean'])}}}",
                f"\\newcommand{{\\DiceGain}}{{{fmt(gain)}}}",
                f"\\newcommand{{\\HardwareName}}{{{best.get('gpu_name', 'TBD').replace('_', '\\_')}}}",
                f"\\newcommand{{\\TorchVersion}}{{{str(best.get('torch_version', 'TBD')).replace('_', '\\_')}}}",
                f"\\newcommand{{\\CudaVersion}}{{{str(best.get('cuda_version', 'TBD')).replace('_', '\\_')}}}",
            ]
        )
    else:
        lines.extend(
            [
                "\\newcommand{\\BestModelName}{TBD}",
                "\\newcommand{\\BestDice}{TBD}",
                "\\newcommand{\\BestIoU}{TBD}",
                "\\newcommand{\\DiceGain}{TBD}",
                "\\newcommand{\\HardwareName}{TBD}",
                "\\newcommand{\\TorchVersion}{TBD}",
                "\\newcommand{\\CudaVersion}{TBD}",
            ]
        )
    for name, prefix in MACRO_PREFIX.items():
        metrics = metrics_by_name.get(name)
        values = (
            {
                "Dice": fmt(metrics["dice_mean"]),
                "IoU": fmt(metrics["iou_mean"]),
                "Precision": fmt(metrics["precision_mean"]),
                "Recall": fmt(metrics["recall_mean"]),
                "HD": fmt(metrics["hd95_pixels_mean"], 2),
                "Params": f"{metrics['parameters']:,}",
                "Latency": fmt(metrics["inference_ms_per_image"], 2),
            }
            if metrics
            else {key: "TBD" for key in METRIC_MACROS}
        )
        for suffix in METRIC_MACROS:
            lines.append(f"\\newcommand{{\\{prefix}{suffix}}}{{{values[suffix]}}}")
    Path("paper/results_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_models(device: torch.device) -> tuple[dict[str, torch.nn.Module], dict]:
    models: dict[str, torch.nn.Module] = {}
    shared_config = None
    for name, run_dir in EXPERIMENTS.items():
        checkpoint_path = run_dir / "checkpoints" / "best.pt"
        checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
        model = build_model(checkpoint["config"]["model"]).to(device)
        model.load_state_dict(checkpoint["model_state"])
        model.eval()
        models[name] = model
        shared_config = checkpoint["config"]
    assert shared_config is not None
    return models, shared_config


def generate_qualitative(device: torch.device, sample_count: int, output_path: Path) -> None:
    models, config = load_models(device)
    loader = build_loaders(config)["test"]
    dataset = loader.dataset
    proposed_metrics = pd.read_csv(EXPERIMENTS["Proposed"] / "per_image_metrics.csv")
    proposed_metrics = proposed_metrics.sort_values("dice")
    worst = proposed_metrics.head(max(sample_count // 2, 1))["name"].tolist()
    best = proposed_metrics.tail(sample_count - len(worst))["name"].tolist()
    selected_names = worst + best
    index_by_name = {item["name"]: i for i, item in enumerate(dataset.items)}
    samples = [dataset[index_by_name[name]] for name in selected_names if name in index_by_name]
    if not samples:
        return
    columns = ["Image", "Ground truth", *models.keys()]
    fig, axes = plt.subplots(len(samples), len(columns), figsize=(3.0 * len(columns), 2.7 * len(samples)), squeeze=False)
    sample_records = []
    for row, sample in enumerate(samples):
        image_t = sample["image"].unsqueeze(0).to(device)
        image_np = denormalize(sample["image"].numpy()).transpose(1, 2, 0)
        mask_np = sample["mask"][0].numpy()
        axes[row, 0].imshow(image_np)
        axes[row, 1].imshow(mask_np, cmap="gray", vmin=0, vmax=1)
        sample_records.append({"name": sample["name"], "selection": "worst" if sample["name"] in worst else "best"})
        with torch.no_grad():
            for col, (name, model) in enumerate(models.items(), start=2):
                pred = (torch.sigmoid(model(image_t))[0, 0].cpu().numpy() >= 0.5).astype(np.float32)
                axes[row, col].imshow(pred, cmap="gray", vmin=0, vmax=1)
        for col, title in enumerate(columns):
            axes[row, col].axis("off")
            if row == 0:
                axes[row, col].set_title(title)
        axes[row, 0].set_ylabel(str(sample["name"]), fontsize=8)
    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    pd.DataFrame(sample_records).to_csv("results/qualitative_samples.csv", index=False)


def main() -> None:
    args = parse_args()
    figure_dir = Path("paper/figures")
    figure_dir.mkdir(parents=True, exist_ok=True)
    histories = {name: path / "history.csv" for name, path in EXPERIMENTS.items() if (path / "history.csv").exists()}
    if histories:
        plot_histories(histories, figure_dir)

    rows = []
    metrics_by_name: dict[str, dict] = {}
    for name, path in EXPERIMENTS.items():
        metrics_path = path / "metrics.json"
        if metrics_path.exists():
            with metrics_path.open("r", encoding="utf-8") as f:
                metrics = json.load(f)
            metrics_by_name[name] = metrics
            rows.append(metrics)
    write_macros(metrics_by_name)
    if not rows:
        print("No metrics were found; placeholder LaTeX macros were retained.")
        return
    df = pd.DataFrame(rows)
    Path("results").mkdir(exist_ok=True)
    df.to_csv("results/summary.csv", index=False)

    labels = list(metrics_by_name)
    dice = [metrics_by_name[n]["dice_mean"] for n in labels]
    plt.figure(figsize=(7, 4.5))
    plt.bar(labels, dice)
    plt.ylabel("Test Dice")
    plt.xticks(rotation=15, ha="right")
    plt.tight_layout()
    plt.savefig(figure_dir / "test_dice_comparison.png", dpi=220)
    plt.close()

    if len(metrics_by_name) == len(EXPERIMENTS):
        device = torch.device(args.device or ("cuda" if torch.cuda.is_available() else "cpu"))
        generate_qualitative(device, args.qualitative_samples, figure_dir / "qualitative_results.png")
    best_name = max(metrics_by_name, key=lambda n: metrics_by_name[n]["dice_mean"])
    print(f"Best model: {best_name}; generated LaTeX macros and paper figures.")


if __name__ == "__main__":
    main()
